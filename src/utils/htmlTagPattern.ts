/**
 * 用正则匹配 HTML 开标签时的属性区片段。
 *
 * 朴素的 `[^>]*` 会在**引号内**的第一个 `>` 处收尾：
 * `<img alt="a>b" src="x.png">` 只被吃掉 `<img alt="a`，
 * 剩下的 `b" src="x.png">` 变成可见正文 —— 既是脏内容，
 * 也会把 Word 图片的本地路径（`file:///C:/Users/…`）泄漏进文档。
 *
 * 这里按「非引号字符 | 双引号串 | 单引号串」交替匹配，引号内的 `>` 不再结束标签。
 * 见约定 22：凡是用正则从 HTML 里摘标签，一律用它拼属性区，不得直接写 `[^>]*`。
 */
export const TAG_INNARDS = `(?:[^>"']|"[^"]*"|'[^']*')*`;
